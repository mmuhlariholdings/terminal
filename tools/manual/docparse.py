def read(rel):
    p = os.path.join(ROOT, rel)
    return open(p, encoding="utf-8").read() if os.path.exists(p) else ""


def md_section(text, title):
    """Markdown section whose heading text starts with `title`, up to the next heading of the same or higher level."""
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        m = re.match(r"^(#+)\s+(.*)$", ln)
        if m and m.group(2).strip().startswith(title):
            level = len(m.group(1))
            body = []
            for ln2 in lines[i + 1:]:
                m2 = re.match(r"^(#+)\s", ln2)
                if m2 and len(m2.group(1)) <= level:
                    break
                body.append(ln2)
            return "\n".join(body).strip()
    return ""


def drop_title(md):
    """Remove a document's own top-level "# Title" line when it's embedded under a section heading."""
    return re.sub(r"\A\s*# .*\n", "", md)


def inline(md):
    """Small inline Markdown to HTML for table cells: **bold**, `code`, ~~strike~~."""
    s = html.escape(md)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"`(.+?)`", r"<code>\1</code>", s)
    s = re.sub(r"~~(.+?)~~", r"<s>\1</s>", s)
    return s


def md_table(block):
    rows = [r for r in block.split("\n") if r.strip().startswith("|")]
    out = []
    for r in rows:
        cells = [c.strip() for c in r.strip().strip("|").split("|")]
        if all(re.fullmatch(r":?-{3,}:?", c) for c in cells if c):
            continue
        out.append(cells)
    return out


def cost_range(cell):
    m = re.search(r"([\d,]+)\s*[–-]\s*([\d,]+)", cell)
    if not m:
        return None
    return int(m.group(1).replace(",", "")), int(m.group(2).replace(",", ""))


def rand(n):
    return "R" + f"{n:,}"


def md_block(md, cls="md"):
    """Raw Markdown in a script tag; the page renders it with marked."""
    safe = md.replace("</script", "<\\/script")
    return f'<div class="{cls}" data-md></div><script type="text/markdown">{safe}</script>'


def export_schematic_svg(stem):
    sch = os.path.join(ROOT, stem + ".kicad_sch")
    outdir = SCHEM_OUT
    os.makedirs(outdir, exist_ok=True)
    if not (os.path.exists(KICAD_CLI) and os.path.exists(sch)):
        return None
    subprocess.run([KICAD_CLI, "sch", "export", "svg", "-o", outdir, sch], capture_output=True, text=True)
    svg = os.path.join(outdir, os.path.basename(stem) + ".svg")
    return svg if os.path.exists(svg) else None


def bom_html(c, plan):
    sec = md_section(plan, c["bom_heading"])
    rows = md_table(sec)
    if not rows:
        return "<p>No bill of materials found in the plan.</p>", None
    head, items = rows[0], rows[1:]
    lo = hi = 0
    stated = None
    trs = []
    for r in items:
        r = r + [""] * (len(head) - len(r))
        item, qty, spec, cost, sup, quote = r[:6]
        rng = cost_range(cost)
        if c["bom_total_label"].lower() in item.lower():
            stated = rng
            continue
        if rng:
            lo += rng[0]; hi += rng[1]
        q = inline(quote) if quote else '<span class="quote-empty">—</span>'
        trs.append(f"<tr><td>{inline(item)}</td><td>{inline(qty)}</td><td>{inline(spec)}</td><td class='num'>{inline(cost)}</td><td>{inline(sup)}</td><td>{q}</td></tr>")
    per_kit = f"{rand(lo * c['qty'])}–{rand(hi * c['qty']).lstrip('R')}"
    trs.append(f"<tr class='total'><td>Total per unit</td><td></td><td>× {c['qty']} per kit = {per_kit}</td><td class='num'>{rand(lo)}–{hi:,}</td><td></td><td></td></tr>")
    table = ("<div class='tablewrap'><table><thead><tr><th>Item</th><th>Qty</th><th>Specification</th><th class='num'>Est. cost (R)</th>"
             "<th>Brands and suppliers</th><th>Quote</th></tr></thead><tbody>" + "".join(trs) + "</tbody></table></div>")
    if stated:
        ok = stated == (lo, hi)
        cls, msg = ("ok", f"Checked: the items add up to {rand(lo)}–{hi:,}, matching the plan's stated total.") if ok else \
            ("bad", f"Mismatch: the items add up to {rand(lo)}–{hi:,}, but the plan states {rand(stated[0])}–{stated[1]:,}. Fix the plan.")
        table += f"<p class='check {cls}'>{msg}</p>"
    return table, (lo, hi)


def checklist_html(md):
    items = re.findall(r"^- \[( |x)\] (.+)$", md, re.M)
    if not items:
        return "<p>No open items listed.</p>", 0, 0
    done = sum(1 for x, _ in items if x == "x")
    lis = "".join(f'<li class="{"done" if x == "x" else ""}">{inline(t)}</li>' for x, t in items)
    pct = round(100 * done / len(items))
    return (f"<p><strong>{done} of {len(items)} done</strong></p><div class='progress' role='img' aria-label='{pct}% done'>"
            f"<span style='width:{pct}%'></span></div><ul class='checklist'>{lis}</ul>"), done, len(items)


def sprint_html(keywords):
    text = read("system/plan/sprint-1-checklist.md")
    rx = re.compile(keywords, re.I)
    out = []
    for ln in text.split("\n"):
        if ln.startswith("|") and rx.search(ln) and "---" not in ln:
            cells = [x.strip() for x in ln.strip().strip("|").split("|")]
            cells = [x for x in cells if x and x != "☐"]
            if cells:
                out.append("<li>" + " · ".join(inline(x) for x in cells[:3]) + "</li>")
    if not out:
        return ""
    return "<h3>Sprint 1 tasks for this component</h3><ul class='checklist'>" + "".join(out) + "</ul><p class='intro' style='margin-top:10px'>From <code>system/plan/sprint-1-checklist.md</code>.</p>"


