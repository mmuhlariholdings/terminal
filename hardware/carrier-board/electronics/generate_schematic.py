def part(ref, name, value=None, **kw):
    lcsc, fp, note = PARTS[name]
    kw.setdefault("desc", note)
    return Part(ref, value or name, footprint=fp, lcsc=lcsc, **kw)


def R(ref, value, net1, net2, desc):
    return two(ref, value, "R", net1, net2, desc, footprint=FP_R0603, lcsc=RESISTORS[value])


def C(ref, value, net1, net2, desc):
    lcsc, fp = CAPACITORS[value]
    return two(ref, value, "C", net1, net2, desc, footprint=fp, lcsc=lcsc)


def LED(ref, name, cathode, anode, desc):
    lcsc, fp, _ = PARTS[name]
    return two(ref, name.replace(" 0603", ""), "LED", cathode, anode, desc + " (pad 1 cathode)", name1="K", name2="A",
               footprint=fp, lcsc=lcsc)


def solder_jumper(ref, value, net1, net2, desc):
    p = two(ref, value, "D2", net1, net2, desc, footprint=FP_SOLDER_JUMPER)
    p.in_bom = False                         # bare copper: open as made, closed with a blob of solder
    return p


def test_pad(ref, net, desc):
    tp = Part(ref, net, left=[P("1", "TP", net)], width=7.62, desc=f"Test pad (back): {desc}", footprint=FP_TEST_PAD)
    tp.in_bom = False
    return tp


