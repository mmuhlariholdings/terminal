#!/usr/bin/env python3
"""Terminal 1 CM4 carrier board schematic, Rev A.

Run:  python3 generate_schematic.py [--erc]
Writes carrier-board.kicad_sch / .kicad_pro (and, with --erc, KiCad's electrical rules check and carrier-board.pdf),
netlist.md, pin-map.md and preview/carrier-board.svg. Edit this script, not the generated files.

What the board does (system/plan/interfaces.md is the source of truth for every shared number and net name):
  - holds a Raspberry Pi Compute Module 4 on two Hirose DF40C-100DS-0.4V receptacles (1.5 mm stacking), on the front;
  - takes +5V_CM4, USB 2.0 and the power-control lines from the keyboard board over the 24-way 0.5 mm FFC (J3);
  - brings DSI1 (4 lanes + clock), the display I2C (SDA0/SCL0 = GPIO44/45, firmware bus "i2c_csi_dsi") and 3.3 V to a
    Raspberry Pi standard 22-way 0.5 mm FPC connector (J4), wired as DISP1 on the CM4 IO board;
  - keeps time with a PCF85063A real-time clock and a CR2032 cell, the same circuit as the CM4 IO board (U8, D3, BT1 there);
  - has status LEDs, a serial console on test pads, solder jumpers for EEPROM write-protect and USB_OTG_ID.
The CM4's own U.FL socket feeds the external flex antenna directly; the carrier has no antenna circuitry.

CM4 pin numbers and names: Raspberry Pi CM4 datasheet table 6 (checked pin by pin against the ComputeModule4-CM4 symbol in
Raspberry Pi's CM4 IO board KiCad files, CM4IOv5). Every pin is either connected or left unconnected with a KiCad no-connect
flag; pin-map.md lists all 200 with the reason.
"""
