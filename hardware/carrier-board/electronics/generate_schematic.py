def unused_reason(name):
    """Why an unconnected CM4 pin is left open (datasheet guidance in brackets)."""
    if name.startswith("Ethernet"):
        return "Ethernet not used in v1 (no PHY magnetics fitted; leave open)"
    if name.startswith("SD_") and name not in ("SD_VDD_OVERRIDE", "SD_PWR_ON"):
        return "SD/eMMC bus: only on CM4Lite; our CM4 has eMMC (leave open)"
    if name in ("SD_VDD_OVERRIDE",):
        return "Only for external eMMC on CM4Lite (datasheet: otherwise leave unconnected)"
    if name == "SD_PWR_ON":
        return "SD card power switch: CM4Lite only (leave open)"
    if name == "Reserved":
        return "Reserved (datasheet: do not connect anything)"
    if name == "CM4_1.8V":
        return "1.8 V output not needed (GPIO bank runs at 3.3 V)"
    if name in ("WL_nDisable", "BT_nDisable"):
        return "Wireless stays enabled (1.8k pull-up inside the CM4; datasheet: can be left floating)"
    if name.startswith("AnalogIP"):
        return "Spare MXL7704 analogue input, not used (100 nF filter on the CM4)"
    if name == "Camera_GPIO":
        return "No camera (datasheet: reassigning not recommended)"
    if name == "nEXTRST":
        return "Reset output for external devices: none on this board"
    if name.startswith("PCIe"):
        return "PCIe not used in v1 (leave open)"
    if name == "VDAC_COMP":
        return "Composite video not used"
    if name.startswith(("CAM0", "CAM1")):
        return "No camera in v1"
    if name.startswith("HDMI"):
        return "No HDMI in v1 (hot-plug inputs have 100k pull-downs inside the CM4)"
    if name.startswith("DSI0"):
        return "DSI0 (2-lane port) not used; the display is on DSI1"
    if name in ("ID_SC", "ID_SD"):
        return "HAT ID I2C (GPIO0/1) not used (no HAT EEPROM)"
    if name.startswith("GPIO"):
        return "Spare GPIO, not used in v1"
    return "Not used"


def cm4_pin(num):
    """Symbol pin for CM4 pin num. The pin NUMBER is the receptacle's pad (1-100 on each DF40); on J2 the pin NAME carries
    the CM4 pin number in brackets, e.g. pad 75 of J2 = "DSI1_D0_N [175]"."""
    name = CM4_PIN_NAMES[num - 1]
    pad = str(num if num <= 100 else num - 100)
    shown = name if num <= 100 else f"{name} [{num}]"
    if name == "GND":
        return P(pad, shown, "GND", "power_in")
    if name == "+5V_IN":
        return P(pad, shown, "+5V_CM4", "power_in")
    if num in CM4_USED:
        net, typ, _ = CM4_USED[num]
        return P(pad, shown, net, typ)
    return P(pad, shown, None, "passive")


