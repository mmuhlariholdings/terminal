"""Project footprint for the Q20 keyboard connector: Hirose BM20B(0.8)-40DS-0.4V(51), 40-pin 0.4 mm board-to-board receptacle.

Written into terminal-1.pretty by generate_schematic.py (KiCad's library has no BM20B footprint).
Pad positions and sizes are the numbers used by Solder Party's BBQ20KBD board (bbq20_keyboard.kicad_pcb, footprint
"Connector_Hirose_Extra:BM20B(0.8)-40DS-0.4V", read 2026-11-16; that design is CERN-OHL-1.2). The numbers here are re-entered
by this script rather than copied as a file. CHECK them against Hirose's BM20B drawing before ordering.
"""
import os
import uuid

NAME = "Hirose_BM20B-0.8-40DS-0.4V"
NS = uuid.UUID("a3e1f0c2-55d4-4b8e-9d6b-2f7c1e0a9b31")


def _u(*k):
    return str(uuid.uuid5(NS, "/".join(map(str, k))))


def _pad(name, x, y, w, h):
    return (f'\t(pad "{name}" smd rect (at {x:.3f} {y:.3f}) (size {w} {h}) (layers "F.Cu" "F.Paste" "F.Mask") '
            f'(uuid "{_u("pad", name)}"))')


def _line(x1, y1, x2, y2, layer, width):
    return (f'\t(fp_line (start {x1} {y1}) (end {x2} {y2}) (stroke (width {width}) (type solid)) (layer "{layer}") '
            f'(uuid "{_u("line", x1, y1, x2, y2, layer)}"))')


def footprint_text():
    out = [f'(footprint "{NAME}" (version 20240108) (generator "terminal1_keyboard_connector") (generator_version "1.0") (layer "F.Cu")',
           '\t(descr "Hirose BM20B(0.8)-40DS-0.4V(51) 40-pin 0.4 mm receptacle for the BlackBerry Q20 keyboard flex. '
           'Pad geometry from the BBQ20KBD board (Solder Party, CERN-OHL-1.2). CHECK against the Hirose drawing. '
           'Generated by hardware/keyboard-board/electronics/keyboard_connector_footprint.py")',
           '\t(attr smd)',
           f'\t(property "Reference" "REF**" (at 0 -2.6 0) (layer "F.SilkS") (uuid "{_u("ref")}") (effects (font (size 0.8 0.8) (thickness 0.12))))',
           f'\t(property "Value" "{NAME}" (at 0 2.6 0) (layer "F.Fab") (uuid "{_u("value")}") (effects (font (size 0.8 0.8) (thickness 0.12))))']
    for i in range(20):                       # pins 1-20 along the top row, left to right
        out.append(_pad(str(1 + i), -3.8 + 0.4 * i, -1.1, 0.23, 0.42))
    for i in range(20):                       # pins 21-40 along the bottom row, right to left
        out.append(_pad(str(21 + i), 3.8 - 0.4 * i, 1.085, 0.23, 0.42))
    for name, x, y in (("MP1", -5.01, -0.925), ("MP2", 5.01, -0.925), ("MP3", 5.01, 0.925), ("MP4", -5.01, 0.925)):
        out.append(_pad(name, x, y, 0.3, 0.75))
    for x1, y1, x2, y2 in ((-5.24, -1.1575, -5.24, 1.1425), (5.24, -1.1575, 5.24, 1.1425), (-4.76, -1.1575, -4.02, -1.1575),
                           (4.01, -1.1575, 4.76, -1.1575), (-4.76, 1.1425, -4.02, 1.1425), (4.01, 1.1425, 4.76, 1.1425),
                           (-4.4, -1.8, -3.9, -1.8)):
        out.append(_line(x1, y1, x2, y2, "F.SilkS", 0.12))
    for x1, y1, x2, y2 in ((-5.6, -1.6, 5.6, -1.6), (5.6, -1.6, 5.6, 1.6), (5.6, 1.6, -5.6, 1.6), (-5.6, 1.6, -5.6, -1.6)):
        out.append(_line(x1, y1, x2, y2, "F.CrtYd", 0.05))
    for x1, y1, x2, y2 in ((-5.0, -1.0, 5.0, -1.0), (5.0, -1.0, 5.0, 1.0), (5.0, 1.0, -5.0, 1.0), (-5.0, 1.0, -5.0, -1.0)):
        out.append(_line(x1, y1, x2, y2, "F.Fab", 0.1))
    out.append(")")
    return "\n".join(out) + "\n"


def write(folder):
    lib = os.path.join(folder, "terminal-1.pretty")
    os.makedirs(lib, exist_ok=True)
    path = os.path.join(lib, NAME + ".kicad_mod")
    with open(path, "w") as fh:
        fh.write(footprint_text())
    return path
