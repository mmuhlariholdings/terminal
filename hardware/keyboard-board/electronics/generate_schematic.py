def check_board_h():
    path = os.path.join(ROOT, "firmware", "keyboard-board", "src", "board.h")
    if not os.path.exists(path):
        return ["board.h not found"]
    defines = dict(re.findall(r"#define (PIN_\w+) (\d+)", open(path).read()))
    problems = []
    for g, (net, _t, _w, define) in PIN_MAP.items():
        if defines.get(define) != str(g):
            problems.append(f"board.h {define} = {defines.get(define)}, schematic GPIO {g} ({net})")
    used = {d for *_x, d in PIN_MAP.values()}
    for d, g in defines.items():
        if d not in used:
            problems.append(f"board.h defines {d} = {g}, not in the schematic pin map")
    return problems


