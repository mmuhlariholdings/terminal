# ------------------------------------------------------------------------------------------------ helpers
class Refs:
    def __init__(self):
        self.n = {}

    def __call__(self, prefix):
        self.n[prefix] = self.n.get(prefix, 0) + 1
        return f"{prefix}{self.n[prefix]}"


ref = Refs()


def part(mpn, prefix, left=(), right=(), width=None, desc="", value=None):
    lcsc, footprint = lookup(mpn)
    return Part(ref(prefix), value or mpn, left=left, right=right, width=width, desc=desc, footprint=footprint, lcsc=lcsc)


def R(value, net1, net2, desc):
    return two(ref("R"), value, "R", net1, net2, desc, footprint=FOOTPRINT_RESISTOR, lcsc=RESISTOR_0603[value])


def C(value, net1, net2, desc):
    lcsc, footprint = CAPACITOR[value]
    return two(ref("C"), value, "C", net1, net2, desc, footprint=footprint, lcsc=lcsc)


def L(mpn, value, net1, net2, desc):
    lcsc, footprint = lookup(mpn)
    return two(ref("L"), value, "R", net1, net2, desc, footprint=footprint, lcsc=lcsc)


def mosfet(mpn, gate, drain, source, desc):
    """N-MOSFET, SOT-23: pin 1 gate, 2 source, 3 drain."""
    return part(mpn, "Q", left=[P("1", "G", gate, "input")], right=[P("3", "D", drain), P("2", "S", source)], width=7.62,
                desc=desc + " (SOT-23: 1 G, 2 S, 3 D)")


class Sheet:
    """Places parts in columns down the A3 sheet so that no two parts' pins or label stubs can touch."""

    def __init__(self, x=20.0, top=22.0, bottom=252.0):
        self.x, self.top, self.bottom = x, top, bottom
        self.y = top
        self.column_width = 0.0

    def add(self, p, gap=2.54):
        g = p.geom()
        h = g.get("h", 2.54)
        w = g["w"] + 2 * 2.54 + 2 * 2.54
        nets = [pin[2] for pin in p.left + p.right if pin[2]]
        label = max([len(n) for n in nets] + [4]) * 0.9          # 1.27 mm text is about 0.9 mm per character
        span = w + 2 * label + 2
        if self.y + h > self.bottom:
            self.next_column()
        self.column_width = max(self.column_width, span)
        sch.add(p, self.x + span / 2 if p.kind != "box" else self.x + label + w / 2 + 1, self.y + h / 2 + 1.27)
        self.y += h + gap + 1.27
        return p

    def next_column(self):
        self.x += self.column_width + 2
        self.y = self.top
        self.column_width = 0.0

    def heading(self, text):
        if self.y + 20 > self.bottom:
            self.next_column()
        sch.note(self.x, self.y, text, 1.6)
        self.y += 5


